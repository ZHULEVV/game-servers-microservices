from typing import Protocol
from uuid import UUID

from app.models.server import Server


class ServerRepoProtocol(Protocol):
    def add(self, server: Server) -> Server: ...
    def get_by_id(self, server_id: UUID) -> Server: ...
    def update(self, server: Server) -> Server: ...
    def list(self, game: str | None, region: str | None, min_slots: int | None, max_price: float | None,
             offset: int, count: int) -> tuple[list[Server], int]: ...
    def is_event_processed(self, event_id: str) -> bool: ...
    def mark_event_processed(self, event_id: str) -> None: ...
