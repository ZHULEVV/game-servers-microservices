from datetime import datetime
from typing import Protocol
from uuid import UUID

from app.models.booking import Booking, BookingStatus


class BookingRepoProtocol(Protocol):
    def add(self, booking: Booking) -> Booking: ...
    def get_by_id(self, booking_id: UUID) -> Booking: ...
    def update(self, booking: Booking) -> Booking: ...
    def list(self, user_id: UUID | None, status: BookingStatus | None, start_from: datetime | None,
             start_to: datetime | None, offset: int, count: int) -> tuple[list[Booking], int]: ...
    def find_overlapping(self, server_id: UUID, start: datetime, end: datetime,
                         exclude_id: UUID | None = None) -> list[Booking]: ...
    def find_expired(self, now: datetime) -> list[Booking]: ...
    def is_event_processed(self, event_id: str) -> bool: ...
    def mark_event_processed(self, event_id: str) -> None: ...
