from typing import Protocol
from uuid import UUID

from app.models.notification import Notification


class NotificationRepoProtocol(Protocol):
    def add(self, note: Notification) -> Notification: ...
    def get_by_id(self, note_id: UUID) -> Notification: ...
    def update(self, note: Notification) -> Notification: ...
    def list(self, user_id: UUID | None, type: str | None, unread: bool | None,
             offset: int, count: int) -> tuple[list[Notification], int]: ...
    def is_event_processed(self, event_id: str) -> bool: ...
    def mark_event_processed(self, event_id: str) -> None: ...
